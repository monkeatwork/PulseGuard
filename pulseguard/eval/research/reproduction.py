"""Writes eval/results/REPRODUCTION.md (HANDOFF.md task 0): every headline
number in the committed eval/results/*.json next to the value a fresh
`make pipeline SEED=42` produced, and whether they match.

Usage (after copying the committed JSONs aside and re-running the pipeline):
    python -m eval.research.reproduction --committed /path/to/committed --fresh eval/results \
        --out eval/results/REPRODUCTION.md
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

TOLERANCE = 1e-9

# (label, file, path into the JSON)
HEADLINE: list[tuple[str, str, tuple]] = []
for det, fname in (("Splunk", "baseline_splunk.json"), ("Elastic", "baseline_elastic.json")):
    for m in ("precision", "recall", "fpr"):
        HEADLINE.append((f"{det} {m}", fname, ("overall", m)))
for label, fname, prefix in (
    ("Stage A+B", "stage_ab.json", ("overall",)),
    ("Stage A alone", "stage_ab.json", ("stage_a_only", "overall")),
    ("Stage B alone", "stage_ab.json", ("stage_b_only", "overall")),
    ("Stage C (GRU)", "stage_c.json", ("overall",)),
    ("Full fusion", "full_fusion.json", ("overall",)),
):
    for m in ("precision", "recall", "fpr"):
        HEADLINE.append((f"{label} {m}", fname, (*prefix, m)))
HEADLINE += [
    ("Stage B threshold", "stage_ab.json", ("threshold",)),
    ("Stage C threshold", "stage_c.json", ("threshold",)),
    ("Fusion weight A", "full_fusion.json", ("weights", "a")),
    ("Fusion weight B", "full_fusion.json", ("weights", "b")),
    ("Fusion weight C", "full_fusion.json", ("weights", "c")),
    ("Fusion threshold", "full_fusion.json", ("threshold",)),
    ("Test episodes evaluated", "full_fusion.json", ("n_episodes_evaluated",)),
]
for variant in ("frequency_only", "frequency_plus_response_behaviour", "response_behaviour_minus_latency_drift_slope"):
    for m in ("precision", "recall", "fpr"):
        HEADLINE.append((f"Ablation {variant} {m}", "ablation.json", ("variants", variant, "overall", m)))
HEADLINE += [
    ("Response-behaviour recall lift (pp)", "ablation.json", ("response_behaviour_lift_percentage_points",)),
    ("latency_drift_slope recall lift (pp)", "ablation.json", ("latency_drift_slope_lift_percentage_points",)),
]
for det in ("splunk", "elastic"):
    for prof in ("mimicry_adversarial", "slow_pacing_adversarial"):
        HEADLINE.append((f"Adversarial {det} {prof} recall", "adversarial.json", ("baselines", det, prof, "recall")))
for det in ("stage_ab", "stage_c", "full_fusion"):
    for prof in ("mimicry_adversarial", "slow_pacing_adversarial"):
        HEADLINE.append((f"Adversarial {det} {prof} recall", "adversarial.json", (det, prof, "recall")))
HEADLINE.append(("Anti-DoS invariant under mimicry", "adversarial.json", ("anti_dos_invariant_holds_under_mimicry_pacing",)))


def _get(d, path):
    for key in path:
        if not isinstance(d, dict) or key not in d:
            return None
        d = d[key]
    return d


def _leaves(d, prefix=()):
    if isinstance(d, dict):
        for k, v in d.items():
            yield from _leaves(v, (*prefix, k))
    elif isinstance(d, list):
        for i, v in enumerate(d):
            yield from _leaves(v, (*prefix, i))
    else:
        yield prefix, d


def _same(a, b) -> bool:
    if isinstance(a, (int, float)) and isinstance(b, (int, float)) and not isinstance(a, bool):
        return abs(a - b) <= TOLERANCE
    return a == b


def _fmt(v) -> str:
    if v is None:
        return "—"
    if isinstance(v, bool):
        return "holds" if v else "VIOLATED"
    if isinstance(v, float):
        return f"{v:.4f}".rstrip("0").rstrip(".") if abs(v) < 1000 else f"{v:.1f}"
    return str(v)


def build(committed: Path, fresh: Path, notes: list[str]) -> str:
    load = lambda root, f: json.loads((root / f).read_text()) if (root / f).exists() else {}  # noqa: E731
    lines = [
        "# Reproduction of the committed results (seed 42)",
        "",
        "_Generated by `python -m eval.research.reproduction`. "
        "Committed = the `eval/results/*.json` in the repository before this run; "
        "reproduced = a fresh `make generate baselines train evaluate report SEED=42` on this machine._",
        "",
        "| Number | Committed | Reproduced | Match |",
        "|---|---|---|---|",
    ]
    n_match = 0
    for label, fname, path in HEADLINE:
        a, b = _get(load(committed, fname), path), _get(load(fresh, fname), path)
        ok = _same(a, b)
        n_match += ok
        lines.append(f"| {label} | {_fmt(a)} | {_fmt(b)} | {'yes' if ok else '**no**'} |")
    lines += ["", f"**{n_match} of {len(HEADLINE)} headline numbers match exactly.**", ""]

    # every numeric leaf of every result file, not only the headline ones
    lines += ["## Every value in every result file", "", "| File | Values | Identical | Differ |", "|---|---|---|---|"]
    diffs = []
    for f in sorted(p.name for p in committed.glob("*.json")):
        old, new = dict(_leaves(load(committed, f))), dict(_leaves(load(fresh, f)))
        keys = sorted(set(old) | set(new), key=str)
        bad = [k for k in keys if not _same(old.get(k), new.get(k))]
        lines.append(f"| `{f}` | {len(keys)} | {len(keys) - len(bad)} | {len(bad)} |")
        diffs += [(f, "/".join(map(str, k)), old.get(k), new.get(k)) for k in bad]
    if diffs:
        lines += ["", "Values that differ:", "", "| File | Path | Committed | Reproduced |", "|---|---|---|---|"]
        lines += [f"| `{f}` | `{p}` | {_fmt(a)} | {_fmt(b)} |" for f, p, a, b in diffs]
    if notes:
        lines += ["", "## Notes", ""] + [f"- {n}" for n in notes]
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--committed", required=True)
    parser.add_argument("--fresh", default="eval/results")
    parser.add_argument("--out", default="eval/results/REPRODUCTION.md")
    parser.add_argument("--note", action="append", default=[], help="a line for the Notes section")
    args = parser.parse_args(argv)
    Path(args.out).write_text(build(Path(args.committed), Path(args.fresh), args.note))
    return 0


if __name__ == "__main__":
    sys.exit(main())
